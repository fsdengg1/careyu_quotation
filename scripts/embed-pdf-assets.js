const fs = require("fs");
const path = require("path");

const assetsDir = path.join(__dirname, "../backend/src/pdf/assets");
const cssPath = path.join(__dirname, "../backend/src/pdf/quotation.css");
const outPath = path.join(__dirname, "../backend/src/pdf/embeddedAssets.js");

function b64(file) {
  return fs.readFileSync(file).toString("base64");
}

const logo = b64(path.join(assetsDir, "careyu-logo.png"));
const cover = b64(path.join(assetsDir, "cover-bg.jpg"));
const extraBold = b64(path.join(assetsDir, "fonts", "Montserrat-ExtraBold.ttf"));
const semiBold = b64(path.join(assetsDir, "fonts", "Montserrat-SemiBold.ttf"));
const css = fs.readFileSync(cssPath, "utf8");
const fontFaceCss = `
    @font-face {
      font-family: "Montserrat";
      font-style: normal;
      font-weight: 800;
      src: url(data:font/ttf;base64,${extraBold}) format("truetype");
    }
    @font-face {
      font-family: "Montserrat";
      font-style: normal;
      font-weight: 600;
      src: url(data:font/ttf;base64,${semiBold}) format("truetype");
    }
  `;

const source = `/* Generated by scripts/embed-pdf-assets.js — do not edit */
module.exports = {
  css: ${JSON.stringify(css)},
  logo: ${JSON.stringify(`data:image/png;base64,${logo}`)},
  cover: ${JSON.stringify(`data:image/jpeg;base64,${cover}`)},
  extraBold: ${JSON.stringify(extraBold)},
  semiBold: ${JSON.stringify(semiBold)},
  fontFaceCss: ${JSON.stringify(fontFaceCss)},
};
`;

fs.writeFileSync(outPath, source);
console.log(`Wrote ${outPath}`);
